#!/usr/bin/env node
/**
 * Reads config/deploy.local.env (or DEPLOY_ENV_FILE) and writes gitignored
 * wrangler.deploy.jsonc files for API / web / email-receiver / infra.
 *
 * Usage:
 *   cp config/deploy.example.env config/deploy.local.env   # edit values
 *   pnpm deploy:configure
 *   pnpm deploy:api
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { syncBrandName } from './sync-brand-name.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const envPath = resolve(root, process.env.DEPLOY_ENV_FILE || 'config/deploy.local.env');

function loadEnv(path) {
  if (!existsSync(path)) {
    console.error(
      `Missing ${path}\nCopy config/deploy.example.env → config/deploy.local.env and fill values.`,
    );
    process.exit(1);
  }
  const out = {};
  for (const line of readFileSync(path, 'utf8').split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const i = trimmed.indexOf('=');
    if (i === -1) continue;
    out[trimmed.slice(0, i).trim()] = trimmed.slice(i + 1).trim();
  }
  return out;
}

function requireKeys(env, keys) {
  const missing = keys.filter((k) => !env[k]);
  if (missing.length) {
    console.error(`Missing keys in ${envPath}: ${missing.join(', ')}`);
    process.exit(1);
  }
}

const env = loadEnv(envPath);
requireKeys(env, [
  'D1_DATABASE_ID',
  'R2_BUCKET_NAME',
  'WEB_HOSTNAME',
  'API_HOSTNAME',
  'CORS_ORIGINS',
  'NUXT_PUBLIC_API_BASE_URL',
]);

